CREATE TABLE usuario
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL,
    correo          VARCHAR(255) NOT NULL UNIQUE,
    contrasena_hash VARCHAR(255) NOT NULL,
    rol             VARCHAR(20)  NOT NULL DEFAULT 'CLIENTE'
        CHECK (rol IN ('CLIENTE', 'ENCARGADO'))
);

CREATE TABLE recurso
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(150) NOT NULL,
    descripcion      TEXT,
    estado_operativo VARCHAR(20)  NOT NULL DEFAULT 'OPERATIVO'
        CHECK (estado_operativo IN (
                                    'OPERATIVO', 'MANTENIMIENTO', 'BAJA'
            ))
);

CREATE TABLE reserva
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_reserva TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_inicio  DATE        NOT NULL,
    fecha_fin     DATE        NOT NULL,
    estado        VARCHAR(20) NOT NULL DEFAULT 'APROBADA'
        CHECK (estado IN (
                          'APROBADA', 'CANCELADA', 'RECHAZADA'
            )),
    usuario_id    BIGINT      NOT NULL REFERENCES usuario (id),
    recurso_id    BIGINT      NOT NULL REFERENCES recurso (id),
    CHECK (fecha_inicio < fecha_fin)
);

CREATE TABLE prestamo
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_entrega    DATE   NOT NULL,
    fecha_devolucion DATE,
    reserva_id       BIGINT NOT NULL UNIQUE REFERENCES reserva (id),
    CHECK (
        fecha_devolucion IS NULL
            OR fecha_devolucion >= fecha_entrega
        )
);



